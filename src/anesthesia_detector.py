"""Step 2b: a classifier that finds notes describing anesthesia.

Usage: python src/anesthesia_detector.py

Why: the LLM is slow on a laptop, so only notes that involve anesthesia should
be sent to it. An "ANESTHESIA:" heading finds most of them, but some notes only
mention anesthesia in the narrative text.

How (weak supervision):
  1. Label = does the note have an "ANESTHESIA:" heading? This label is free and
     reliable, because the heading is structured.
  2. Hide every line that starts with "ANESTHE..." before training, so the model
     cannot just look for the heading. It has to learn from the rest of the note
     (procedure words, operating-room language, and so on).
  3. Measure it with 5-fold cross-validation (precision, recall, F1, ROC-AUC).
  4. Score notes WITHOUT a heading and check how many of the narrative-only
     notes found by keyword search it also finds.

Outputs: data/processed/detector_scores.csv and reports/anesthesia_detector.md
"""
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import f1_score, precision_score, recall_score, roc_auc_score
from sklearn.model_selection import StratifiedKFold, cross_val_predict
from sklearn.pipeline import make_pipeline

sys.path.insert(0, str(Path(__file__).parent))
from common import PROCESSED, REPORTS, load_notes  # noqa: E402

THRESHOLD = 0.5
ANESTHESIA_WORDS = re.compile(r"anesthe|sedation|intubat", re.IGNORECASE)
HEADING_LINE = re.compile(r"^[^\n]*\bANESTHE[^\n]*:[^\n]*$", re.IGNORECASE | re.MULTILINE)


def mask_heading(text: str) -> str:
    """Remove lines like 'ANESTHESIA: General.' or 'ANESTHESIOLOGIST: Dr. X'."""
    return HEADING_LINE.sub(" ", text)


def make_model():
    return make_pipeline(
        TfidfVectorizer(ngram_range=(1, 2), min_df=2, max_features=30000, sublinear_tf=True),
        LogisticRegression(max_iter=2000, class_weight="balanced"))


def main() -> None:
    notes = load_notes()
    X = notes["text"].map(mask_heading)
    y = notes["has_anesthesia_heading"].astype(int)

    # 1) honest estimate: every note is scored by a model that never saw it
    cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
    oof = cross_val_predict(make_model(), X, y, cv=cv, method="predict_proba")[:, 1]
    pred = (oof >= THRESHOLD).astype(int)
    metrics = {"precision": precision_score(y, pred), "recall": recall_score(y, pred),
               "f1": f1_score(y, pred), "roc_auc": roc_auc_score(y, oof)}

    notes["detector_score"] = oof
    notes["detector_flag"] = pred.astype(bool)
    no_head = notes[~notes["has_anesthesia_heading"]]
    narrative = no_head[no_head["has_anesthesia_narrative"]]
    caught = narrative["detector_flag"].mean() if len(narrative) else np.nan
    extra = no_head[no_head["detector_flag"] & ~no_head["has_anesthesia_narrative"]]
    flagged_no_head = no_head[no_head["detector_flag"]]
    mentions = flagged_no_head["text"].str.contains(ANESTHESIA_WORDS).mean()

    notes["extraction_candidate"] = (notes["has_anesthesia_heading"]
                                     | notes["has_anesthesia_narrative"]
                                     | notes["detector_flag"])
    notes[["note_id", "detector_score", "detector_flag", "extraction_candidate"]].to_csv(
        PROCESSED / "detector_scores.csv", index=False)
    write_report(notes, metrics, narrative, caught, extra, flagged_no_head, mentions)
    print({k: round(v, 3) for k, v in metrics.items()})
    print(f"narrative-only notes also flagged: {caught:.0%}; "
          f"extra notes flagged for review: {len(extra)}; "
          f"extraction candidates: {notes['extraction_candidate'].sum()}")


def write_report(notes, m, narrative, caught, extra, flagged_no_head, mentions) -> None:
    top_extra = extra.sort_values("detector_score", ascending=False).head(10)
    lines = [
        "# Anesthesia note detector", "",
        "Generated by `src/anesthesia_detector.py`.", "",
        "TF-IDF + logistic regression, trained to predict whether a note has an "
        "\"ANESTHESIA:\" heading **with every anesthesia heading line removed from the text**, "
        "so it has to learn from the rest of the note. Scores are out-of-fold "
        f"(5-fold cross-validation), threshold {THRESHOLD}.", "",
        "| Metric | Value |", "|---|---:|",
        f"| Precision | {m['precision']:.2f} |", f"| Recall | {m['recall']:.2f} |",
        f"| F1 | {m['f1']:.2f} |", f"| ROC-AUC | {m['roc_auc']:.3f} |", "",
        "**Precision is a lower bound.** The training label (\"has a heading\") misses notes "
        "that describe anesthesia without one. Of the "
        f"{len(flagged_no_head)} notes the detector flags that have no heading, "
        f"{mentions:.0%} mention anesthesia, sedation or intubation somewhere in the text "
        "(some only in passing, such as \"anesthetic risks were discussed\"). Many of these "
        "\"false positives\" are real operative notes.", "",
        "## Notes without a heading", "",
        f"- Keyword search found **{len(narrative)}** notes that mention anesthesia only in "
        f"the narrative. The detector also flags **{caught:.0%}** of them, without being "
        "trained on any of them.",
        f"- It flags **{len(extra)}** more notes that neither the heading nor the keywords "
        "found. These are worth a manual look; the top ones by score are listed below.",
        f"- Notes sent to extraction (heading, keywords or detector): "
        f"**{int(notes['extraction_candidate'].sum()):,}** of {len(notes):,}.", "",
        "| Score | Note | Description |", "|---:|---|---|"]
    for _, r in top_extra.iterrows():
        desc = str(r["description"]).replace("|", "/")[:90]
        lines.append(f"| {r['detector_score']:.2f} | {r['sample_name']} | {desc} |")
    (REPORTS / "anesthesia_detector.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
